// Token Radar, model radar-2.
//
// One sealed snapshot in, one ranked board out. The board ranks pre-token
// protocols only: a protocol is pre-token when its snapshot record carries
// no token at all (no market cap, no CoinGecko id, no symbol). Protocols
// whose token already trades are kept apart as the Live view, shown at the
// market's own value, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures, the same
// function for every protocol, no name ever special-cased:
//
//   base      = tvl_usd * 0.25
//   growth    = clamp(change_7d, -60, 120) per cent; unknown growth counts 0
//   growthMult    = 1 + (growth / 100) * 0.5
//   maturity  = 0.6 + min(age_days, 1095) / 1095 * 0.4; unknown age counts 365
//   breadth   = 1 + 0.02 * min(chains - 1, 5)
//   implied   = max(1, round(base * growthMult * maturity * breadth))
//
// TVL is the size of the claim, growth is its momentum, maturity is how
// long it has run with no token (older, still pre-token, is a stronger
// signal that a launch would be large, not a weaker one), and breadth is
// how many chains its TVL sits on. The dashboard recomputes every row
// from these same figures, so the page and board.json always agree.
//
// The board covers the snapshot's whole watchlist (the floor, never the
// ceiling) and adds pre-token protocols below the floor, by TVL, as the
// early radar: protocols the floor leaves out are still worth finding.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.25,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  breadth_per_chain: 0.02,
  breadth_max_chains: 5,
};

export const MODEL_VERSION = 'radar-2';
export const EARLY_ROWS = 160;
export const LIVE_ROWS = 24;

